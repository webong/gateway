// Command gen writes plugins_gen.go from plugins.txt.
//
// Go imports are resolved at compile time, so a static guest must be linked
// into the binary. This generator removes the hand-written import list and
// switch: edit plugins.txt, run "go generate ./...", and the composition map
// is regenerated. Guests not listed here can still be loaded at runtime.
package main

import (
	"bufio"
	"fmt"
	"log"
	"os"
	"sort"
	"strings"
)

const (
	manifest = "plugins.txt"
	output   = "plugins_gen.go"
)

func main() {
	file, err := os.Open(manifest)
	if err != nil {
		log.Fatalf("gen: open %s: %v", manifest, err)
	}
	defer file.Close()

	type entry struct{ name, path string }
	var entries []entry

	scanner := bufio.NewScanner(file)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) != 2 {
			log.Fatalf("gen: %s: want \"<language> <import path>\", got %q", manifest, line)
		}
		entries = append(entries, entry{name: fields[0], path: fields[1]})
	}
	if err := scanner.Err(); err != nil {
		log.Fatalf("gen: read %s: %v", manifest, err)
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].name < entries[j].name })

	var b strings.Builder
	b.WriteString("// Code generated by go generate; DO NOT EDIT.\n")
	b.WriteString("// Source: plugins.txt\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("import (\n")
	b.WriteString("\t\"github.com/webong/gateway/driver/automation\"\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%s %q\n", alias(e.name), e.path)
	}
	b.WriteString(")\n\n")
	b.WriteString("// staticPlugins maps a language to its compiled-in guest entrypoint.\n")
	b.WriteString("var staticPlugins = map[string]func() (automation.Engine, error){\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t%q: %s.Plugin,\n", e.name, alias(e.name))
	}
	b.WriteString("}\n")

	if err := os.WriteFile(output, []byte(b.String()), 0o644); err != nil {
		log.Fatalf("gen: write %s: %v", output, err)
	}
}

// alias turns a language name into a safe, unique import alias.
func alias(name string) string {
	var b strings.Builder
	b.WriteString("plugin_")
	for _, r := range name {
		switch {
		case r >= 'a' && r <= 'z', r >= 'A' && r <= 'Z', r >= '0' && r <= '9':
			b.WriteRune(r)
		default:
			b.WriteRune('_')
		}
	}
	return b.String()
}
